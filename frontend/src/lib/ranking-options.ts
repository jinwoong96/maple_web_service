/** 숫자로 오는 랭킹 파라미터의 뜻.
 *
 * 넥슨은 `world_type`·`ranking_type`·`difficulty`를 숫자로만 받는다. 어느
 * 숫자가 무엇인지는 문서에 없어서 한동안 0으로 하드코딩하고 선택 UI를 만들지
 * 않았다. 2026-09-27에 실측으로 확정했다.
 */

export interface NumericRankingOption {
  value: number
  label: string
}

/** 종합 랭킹의 월드 구분.
 *
 * `date=2026-09-26` 1쪽을 받아 월드 이름을 세어 확정했다. 0은 루나·엘리시움·
 * 스카니아·크로아·베라·오로라·제니스·이노시스·유니온·레드, 1은 에오스·
 * 핼리오스만 나온다. 2는 400이다.
 *
 * **월드 이름을 같이 넣으면 넥슨이 이 값을 무시한다** — `world_name=에오스`에
 * `world_type` 0과 1을 각각 넣어 같은 결과가 왔다. 그래서 화면에서는 월드를
 * 고르면 이 선택을 잠근다. */
export const WORLD_TYPES: readonly NumericRankingOption[] = [
  { value: 0, label: '일반 월드' },
  { value: 1, label: '리부트' },
]

/** 길드 랭킹 종류.
 *
 * 홈페이지 길드 랭킹의 탭 순서(주간명성치 / 플래그레이스 / 지하수로)와 같다.
 * 숫자와 탭을 이렇게 맞춘 근거는 값의 모양이다 — `길드 A`를
 * 2026-09-20~26 하루씩 받아 보면
 *
 * - 셋 다 주가 바뀌는 자리(9/24 목 → 9/25 금)에서 함께 초기화된다. 길드 주간
 *   기록은 목요일 자정에 정산되므로 셋 다 **주간** 값이다.
 * - `1`은 1,000의 배수만 나온다(19000, 22000, 26000…). 플래그 레이스 점수가
 *   1,000점 단위다 — 우리 길드 관리에 저장된 플래그 점수도 1,000의 배수다.
 * - `2`는 2,500만 대로 가장 크다. 저장된 지하 수로 점수가 1인당 20만 대이고
 *   길드원이 200명 가까우므로 자리 수가 맞는다.
 * - `0`은 530만 대인데, 길드 기본 정보의 누적 명성치(6,874만)도 GP(1,000만)도
 *   아니다. 남는 것은 주간 획득 명성치다.
 *
 * 생략하면 400이므로 화면은 항상 하나를 골라 보낸다. */
export const GUILD_RANKING_TYPES: readonly NumericRankingOption[] = [
  { value: 0, label: '주간 명성치' },
  { value: 1, label: '플래그 레이스' },
  { value: 2, label: '지하 수로' },
]

/** 무릉도장 구간.
 *
 * 홈페이지 무릉도장 랭킹의 라디오 버튼이 `t=0` 입문, `t=1` 통달이고, API도
 * 같은 순서다. 전체 월드로 받아 보면 0은 Lv.128~205 / 1~38층 44줄, 1은
 * Lv.286~300 / 82~100층 200줄 — 입문에 사람이 거의 없고 통달이 꽉 차 있는
 * 지금 상태와 맞는다. 2는 400이다.
 *
 * 생략하면 400이므로 화면은 항상 하나를 골라 보낸다. */
export const DOJANG_DIFFICULTIES: readonly NumericRankingOption[] = [
  { value: 0, label: '입문' },
  { value: 1, label: '통달' },
]

/** 처음 열었을 때 보이는 구간.
 *
 * 홈페이지는 입문이 기본인데 우리는 통달로 둔다. 입문은 전체 월드를 통틀어
 * 44줄뿐이라 "1위 Lv.200 31층"이 뜨고, 그걸 본 사람은 랭킹이 고장 난 줄
 * 안다. 사람이 몰려 있는 쪽이 기본이어야 한다. */
export const DEFAULT_DOJANG_DIFFICULTY = 1
